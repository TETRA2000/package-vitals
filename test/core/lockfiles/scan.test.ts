const REPO = 'TETRA2000/slack-deck';
const TREE = `/repos/${REPO}/git/trees/HEAD?recursive=1`;
const shaOf = (path: string) => createHash('sha1').update(path).digest('hex');
const blobUrl = (path: string) => `/repos/${REPO}/git/blobs/${shaOf(path)}`;
const client = (f: ReturnType<typeof fakeFetch>) => new GitHubClient({ token: 't', fetch: f });

/**
 * A fake repo: every file is a blob in the tree, served at a sha made from its path.
 * `sizes` overrides a tree entry's size (null leaves it out), and `routes` overrides responses.
 */
function fakeRepo(
  files: Record<string, string>,
  o: { sizes?: Record<string, number | null>; routes?: Record<string, FakeRoute>; truncated?: boolean } = {},
) {
  const entries = Object.entries(files).map(([path, text]) => {
    const size = o.sizes && path in o.sizes ? o.sizes[path] : Buffer.byteLength(text);
    return { path, sha: shaOf(path), ...(size === null ? {} : { size }) };
  });
  const routes: Record<string, FakeRoute> = { [TREE]: { body: treeJson(entries, { truncated: o.truncated }) } };
  for (const [path, text] of Object.entries(files)) routes[blobUrl(path)] = { body: blobJson(text) };
  return fakeFetch({ ...routes, ...o.routes });
}

const scan = (f: ReturnType<typeof fakeFetch>) => scanRepoLockfiles(client(f), REPO);
const requested = (f: ReturnType<typeof fakeFetch>) => f.calls.map((c) => new URL(c.url).pathname + new URL(c.url).search);

function graphOf(r: ParseResult): DepGraph {
  if (r.status !== 'ok') throw new Error(`expected ok, got ${r.status}: ${r.message}`);
  return r.graph;
}

function project(projects: ProjectScan[], path: string): ProjectScan {
  const p = projects.find((x) => x.path === path);
  if (!p) throw new Error(`no project ${path}`);
  return p;
}

