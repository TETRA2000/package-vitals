import { describe, it, expect } from "vitest";
import { parseYarnLock } from "../../../src/core/lockfiles/yarn.js";
import type { PackageJson } from "../../../src/core/lockfiles/package-json.js";
import {
  chainsTo,
  devOnly,
  isComplete,
  type DepGraph,
  type ParseResult,
} from "../../../src/core/lockfiles/graph.js";

const packageJson = (fields: Partial<PackageJson>): PackageJson => ({
  name: null,
  dependencies: new Map(),
  devDependencies: new Map(),
  optionalDependencies: new Map(),
  peerDependencies: new Map(),
  scripts: new Map(),
  workspaces: [],
  ...fields,
});
const map = (o: Record<string, string>) => new Map(Object.entries(o));
const root = (fields: Partial<PackageJson>, path = ".") => ({
  path,
  packageJson: packageJson(fields),
});

/** The graph of an `ok` result, checked against the shape every parser keeps. */
function graphOf(r: ParseResult): DepGraph {
  if (r.status !== "ok")
    throw new Error(`expected ok, got ${r.status}: ${r.message}`);
  const g = r.graph;
  expect(g.edges).toHaveLength(g.nodes.length);
  g.nodes.forEach((n, i) => expect(n.id).toBe(i));
  for (const e of [...g.roots.flatMap((x) => x.edges), ...g.edges.flat()]) {
    expect(Number.isInteger(e.to) && e.to >= 0 && e.to < g.nodes.length).toBe(
      true,
    );
  }
  return g;
}

const at = (g: DepGraph, id: number) =>
  `${g.nodes[id]!.name}@${g.nodes[id]!.version}`;
const idOf = (g: DepGraph, name: string, version?: string) => {
  const id = g.nodes.findIndex(
    (n) => n.name === name && (version === undefined || n.version === version),
  );
  if (id < 0) throw new Error(`no node ${name}`);
  return id;
};

const HEADER =
  "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n";
const lock = (body: string) => HEADER + body;

const LODASH = `
"lodash@^4.17.0", lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#abc"
  integrity sha512-xyz
`;

describe("parseYarnLock", () => {
  it("reads entries, shared descriptors, and dependencies", () => {
    const g = graphOf(
      parseYarnLock(
        lock(`${LODASH}
"@babel/core@^7.0.0":
  version "7.1.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.1.0.tgz#d"
  dependencies:
    lodash "^4.17.0"
    "@scope/opt" "^1.0.0"
  optionalDependencies:
    "@scope/opt" "^1.0.0"
    missing "^1.0.0"

"@scope/opt@^1.0.0":
  version "1.0.0"
  resolved "git+ssh://git@github.com/a/b.git#abc"

lodash@^3.0.0:
  version "3.10.1"
`),
        [
          root({
            name: "app",
            dependencies: map({ "@babel/core": "^7.0.0", lodash: "^4.17.21" }),
          }),
        ],
      ),
    );
    expect(g.format).toBe("yarn-v1");
    expect(
      g.nodes.map((n) => [n.name, n.version, n.registry, n.lockDev]),
    ).toEqual([
      ["lodash", "4.17.21", true, null],
      ["@babel/core", "7.1.0", true, null],
      ["@scope/opt", "1.0.0", false, null],
      ["lodash", "3.10.1", true, null],
    ]);
    expect(g.edges[1]!.map((e) => [at(g, e.to), e.kind])).toEqual([
      ["@scope/opt@1.0.0", "optional"],
      ["lodash@4.17.21", "prod"],
    ]);
    expect(g.roots[0]!.edges.map((e) => [at(g, e.to), e.kind])).toEqual([
      ["@babel/core@7.1.0", "prod"],
      ["lodash@4.17.21", "prod"],
    ]);
    expect(g.unresolved).toEqual([]);
  });

  it("roots come from package.json files", () => {
    const g = graphOf(
      parseYarnLock(
        lock(`
jest@^29.0.0:
  version "29.0.0"
  dependencies:
    chalk "^4.0.0"

chalk@^4.0.0:
  version "4.1.0"

react@^18.0.0:
  version "18.0.0"
`),
        [
          root({
            name: "app",
            dependencies: map({ react: "^18.0.0" }),
            devDependencies: map({ jest: "^29.0.0" }),
          }),
          root(
            { name: "ws", dependencies: map({ react: "^18.0.0" }) },
            "packages/ws",
          ),
          root({}, "packages/unnamed"),
        ],
      ),
    );
    expect(g.roots.map((r) => [r.label, r.path])).toEqual([
      ["app", "."],
      ["ws", "packages/ws"],
      ["packages/unnamed", "packages/unnamed"],
    ]);
    expect(g.roots[0]!.edges.map((e) => [at(g, e.to), e.kind])).toEqual([
      ["react@18.0.0", "prod"],
      ["jest@29.0.0", "dev"],
    ]);
    expect(isComplete(g)).toBe(true);
    expect(devOnly(g, [idOf(g, "chalk")])).toBe(true);
    expect(devOnly(g, [idOf(g, "react")])).toBe(false);
    expect(chainsTo(g, [idOf(g, "chalk")]).chains).toEqual([
      {
        root: "app",
        links: [
          { name: "jest", version: "29.0.0" },
          { name: "chalk", version: "4.1.0" },
        ],
        dev: true,
      },
    ]);
  });

  it("a name in dev and prod gets an edge per map, and optional wins over prod", () => {
    const g = graphOf(
      parseYarnLock(
        lock('a@^1.0.0:\n  version "1.0.0"\n\nb@^1.0.0:\n  version "1.0.0"\n'),
        [
          root({
            dependencies: map({ a: "^1.0.0", b: "^1.0.0" }),
            devDependencies: map({ a: "^1.0.0" }),
            optionalDependencies: map({ b: "^1.0.0", gone: "^1.0.0" }),
          }),
        ],
      ),
    );
    expect(g.roots[0]!.edges.map((e) => [at(g, e.to), e.kind])).toEqual([
      ["b@1.0.0", "optional"],
      ["a@1.0.0", "prod"],
      ["a@1.0.0", "dev"],
    ]);
    expect(g.unresolved).toEqual([]);
  });

  it("npm: aliases name the real package", () => {
    const g = graphOf(
      parseYarnLock(
        lock(`
"string-width-cjs@npm:string-width@^4.2.0":
  version "4.2.3"
  resolved "https://registry.yarnpkg.com/string-width/-/string-width-4.2.3.tgz#x"
`),
        [
          root({
            name: "app",
            dependencies: map({
              "string-width-cjs": "npm:string-width@^4.2.0",
            }),
          }),
        ],
      ),
    );
    expect(g.nodes.map((n) => n.name)).toEqual(["string-width"]);
    expect(g.roots[0]!.edges).toEqual([{ to: 0, kind: "prod" }]);
    expect(g.unresolved).toEqual([]);
  });

  it("workspace packages are roots, not nodes", () => {
    const g = graphOf(
      parseYarnLock(lock(LODASH), [
        root({
          name: "app",
          dependencies: map({ ws: "1.0.0", lodash: "^4.17.21" }),
        }),
        root(
          { name: "ws", dependencies: map({ lodash: "^4.17.0" }) },
          "packages/ws",
        ),
      ]),
    );
    expect(g.nodes).toHaveLength(1);
    expect(g.roots.map((r) => r.edges.length)).toEqual([1, 1]);
    expect(g.unresolved).toEqual([]);
  });

  it("records unresolved required dependencies", () => {
    const g = graphOf(
      parseYarnLock(
        lock(`
a@^1.0.0:
  version "1.0.0"
  dependencies:
    b "^2.0.0"
  optionalDependencies:
    c "^1.0.0"
`),
        [
          root({
            name: "app",
            dependencies: map({ a: "^1.0.0", z: "^1.0.0" }),
          }),
        ],
      ),
    );
    expect(g.unresolved).toEqual(["a > b", "app > z"]);
    expect(isComplete(g)).toBe(false);
    expect(devOnly(g, [0])).toBeNull();
  });

  it("with no roots the graph is incomplete", () => {
    const g = graphOf(parseYarnLock(lock(LODASH), []));
    expect(g.roots).toEqual([]);
    expect(isComplete(g)).toBe(false);
  });

  it("ignores a BOM and CRLF line endings", () => {
    const g = graphOf(
      parseYarnLock("\uFEFF" + lock(LODASH).replace(/\n/g, "\r\n"), []),
    );
    expect(g.nodes.map((n) => at(g, n.id))).toEqual(["lodash@4.17.21"]);
  });

  it("a non-registry or other-host resolved is not a registry package", () => {
    const g = graphOf(
      parseYarnLock(
        lock(`
a@1.0.0:
  version "1.0.0"
  resolved "https://example.com/a.tgz"

b@file:../b:
  version "1.0.0"
  resolved "file:../b"

c@1.0.0:
  version "1.0.0"
  resolved "https://registry.npmjs.org/c/-/c-1.0.0.tgz"

d@1.0.0:
  version "1.0.0"
`),
        [],
      ),
    );
    expect(g.nodes.map((n) => n.registry)).toEqual([false, false, true, true]);
  });

  it("berry, conflict markers, and broken files", () => {
    expect(parseYarnLock("__metadata:\n  version: 6\n", [])).toEqual({
      status: "unsupported",
      format: "yarn-berry",
      message: "Yarn 2+ lockfiles aren't supported yet.",
    });
    expect(parseYarnLock('a@1:\n  version "1"\n<<<<<<< HEAD\n', [])).toEqual({
      status: "error",
      message: "The lockfile has merge conflict markers.",
    });
    const bad = (text: string, line: number) =>
      expect(parseYarnLock(text, [])).toEqual({
        status: "error",
        message: `Not a valid yarn.lock file (line ${line}).`,
      });
    bad("# c\nnot a header\n", 2);
    bad('  version "1"\n', 1);
    bad('a@1:\n   version "1"\n', 2);
    bad("a@1:\n  version\n", 2);
    bad('a@1:\n  version "1\n', 2);
    bad("a@1:\n  dependencies:\n    b\n", 3);
    bad('a@1:\n  version "1"\n    b "1"\n', 3);
    bad('a@1:\n\tversion "1"\n', 2);
    bad('"a@1" b:\n', 1);
    bad("a@1, :\n", 1);
  });

  it("a duplicate descriptor falls back to the generic error", () => {
    expect(
      parseYarnLock('a@1:\n  version "1"\n\na@1:\n  version "2"\n', []),
    ).toEqual({
      status: "error",
      message: "Couldn't read this lockfile.",
    });
  });

  it("hostile names", () => {
    const before = Object.getOwnPropertyNames(Object.prototype).sort();
    const g = graphOf(
      parseYarnLock(
        lock(`
"__proto__@^1.0.0":
  version "1.0.0"
  dependencies:
    constructor "^1.0.0"

constructor@^1.0.0:
  version "1.0.0"
`),
        [
          root({
            name: "app",
            dependencies: new Map([
              ["__proto__", "^1.0.0"],
              ["toString", "^1.0.0"],
            ]),
          }),
        ],
      ),
    );
    expect(g.nodes.map((n) => n.name)).toEqual(["__proto__", "constructor"]);
    expect(g.edges[0]).toEqual([{ to: 1, kind: "prod" }]);
    expect(g.roots[0]!.edges).toEqual([{ to: 0, kind: "prod" }]);
    expect(g.unresolved).toEqual(["app > toString"]);
    expect(Object.getOwnPropertyNames(Object.prototype).sort()).toEqual(before);
    expect(({} as Record<string, unknown>)["version"]).toBeUndefined();
  });

  it("reads a large lockfile in one pass", () => {
    let body = "";
    for (let i = 0; i < 20000; i++)
      body += `p${i}@^1.0.0:\n  version "1.0.0"\n  dependencies:\n    p${i + 1} "^1.0.0"\n\n`;
    const r = parseYarnLock(lock(body), []);
    expect(r.status).toBe("ok");
  });
});
